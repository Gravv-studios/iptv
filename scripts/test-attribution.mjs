import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require = createRequire(new URL('../outputs/payment-tests/tests.cjs', import.meta.url));
const browser = require('./lib/meta-browser.js');
const {orderInput} = require('./lib/payments/validation.js');
const data = new Map(), cookies = new Map();
globalThis.localStorage = {getItem:k=>data.get(k)??null,setItem:(k,v)=>data.set(k,v),removeItem:k=>data.delete(k)};
globalThis.window = {location:{search:'?utm_source=facebook&utm_medium=paid_social&campaign_id=123&fbclid=test-click',protocol:'https:'}};
globalThis.document = {};
Object.defineProperty(document,'cookie',{get:()=>[...cookies].map(([k,v])=>`${k}=${v}`).join('; '),set:value=>{const [k,v]=value.split(';')[0].split('=');cookies.set(k,v);}});
assert.equal(browser.checkoutAttribution(),undefined);
assert.equal(data.size,0); assert.equal(cookies.size,0);
localStorage.setItem(browser.consentKey,'accepted');
const first = browser.checkoutAttribution();
assert.equal(first.campaign.campaign_id,'123'); assert.match(first.fbc,/^fb\.1\.\d+\.test-click$/);
window.location.search='';
assert.deepEqual(browser.checkoutAttribution(),first);
window.location.search='?utm_source=whatsapp&utm_medium=chat';
assert.equal(browser.checkoutAttribution().campaign.utm_source,'whatsapp');
assert.equal(browser.checkoutAttribution().campaign.campaign_id,undefined);
cookies.clear();
assert.equal(browser.checkoutAttribution().fbc,undefined); // Never manufacture ad click IDs from a chat link.
window.location.search='?utm_source=user%40example.com&ad_id={{ad.id}}&fbclid=%3Cscript%3E';
assert.equal(browser.checkoutAttribution().fbc,undefined);
assert.equal(browser.checkoutAttribution().campaign.utm_source,'whatsapp');
window.location.search='';
data.set(browser.attributionKey,JSON.stringify({capturedAt:Date.now()-91*86400*1000,campaign:{utm_source:'old'}}));
assert.equal(browser.checkoutAttribution().campaign,undefined);
data.set(browser.attributionKey,'invalid-json');
assert.equal(browser.checkoutAttribution().campaign,undefined);
const parsed=orderInput.parse({requestKey:'11111111-1111-4111-8111-111111111111',planId:'mensal',customerName:'Teste Sintético',email:'test@example.invalid',phone:'61999999999',attribution:{consent:true,fbp:'invalid',fbc:first.fbc,campaign:{utm_source:'facebook',email:'private',ad_id:'123'}}});
assert.equal(parsed.attribution.fbc,first.fbc); assert.equal(parsed.attribution.fbp,undefined);
assert.deepEqual(parsed.attribution.campaign,{utm_source:'facebook',ad_id:'123'});
browser.clearCampaignAttribution(); localStorage.setItem(browser.consentKey,'rejected');
assert.equal(browser.checkoutAttribution(),undefined);
console.log('OK: consent, tagged landing, navigation, channel change, no invented clicks, expiry, invalid input and server preservation. No network or real orders.');
